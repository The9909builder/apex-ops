#!/usr/bin/env python3
"""
SUPER-REASONER (OMNIREASON v4.0) selftest.

One command that re-verifies the v4 mechanics on the real shipped files. Run after any
edit to SKILL.md, spec.yaml, validations.yaml, or evals.yaml; run before evals.

    python3 scripts/selftest.py

Every mechanism check is a real PAIR: a positive assertion that the mechanism is present,
and a negative (mutation) assertion that removing it is DETECTED. The negative half is the
point. A check that cannot fail is not a check; the whole reason v1.0 through v3.0 shipped
the same weakness three times is that their gates could not fail.

The named RED tests (the conditions that must stay detectable forever):
  - `axes-collapse`            : the grounding axis exists AND a receipt path exists, so the
                                 three axes can be correlated on real data
  - `panel-is-selfscore-in-costume` : no verdict without a panel that did not write the candidates
  - `judge-is-yes-man`         : refute-default is stated, so an all-pass panel is a failure
  - `pinned-floor-unlearnable` : EXPLORATION routing + falsifiability are floors, and a profile
                                 that down-weights them BLOCKS
  - `receipt-never-arrives`    : the prediction block is scored against a recorded outcome

Exit 0 = all green. Any failure prints the failed check name and exits 1.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SKILL_DIR = HERE.parent
SKILL = SKILL_DIR / "SKILL.md"
SPEC = SKILL_DIR / "spec.yaml"
EVALS = SKILL_DIR / "evals.yaml"

REQUIRED_SECTIONS = [
    "## PHASE 0: PRECOMMIT + CLASSIFY",
    "## ROUTE",
    "## PANEL",
    "## FALSIFIABILITY",
    "## PREDICTION",
]

RESULTS: list[tuple[str, bool, str]] = []


class Failed(AssertionError):
    pass


def require(cond: bool, detail: str) -> None:
    if not cond:
        raise Failed(detail)


def check(name: str, fn) -> None:
    try:
        note = fn() or ""
        RESULTS.append((name, True, note))
        print(f"  PASS  {name}" + (f"  ({note})" if note else ""))
    except Exception as exc:  # noqa: BLE001 - selftest reports anything
        RESULTS.append((name, False, str(exc)))
        print(f"  FAIL  {name}\n          {exc}")


def load() -> tuple[str, dict, dict]:
    md = SKILL.read_text(encoding="utf-8")
    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    evals = yaml.safe_load(EVALS.read_text(encoding="utf-8"))
    return md, spec, evals


MD, SPEC, EVALS = load()


def strip_managed(md: str) -> str:
    """Return SKILL.md with the tfc_install-managed preamble hook removed.

    The managed block is regenerated by tfc_install, so it is exempt from authoring rules;
    everything outside it is the skill's own prose and must obey them.
    """
    start = md.find("<!-- TFC:PREAMBLE-HOOK START -->")
    end = md.find("<!-- TFC:PREAMBLE-HOOK END -->")
    if start == -1 or end == -1:
        return md
    return md[:start] + md[end:]


# ── mechanism predicates (each takes the md text, so a mutation can be fed in) ──


def p_three_axes(md: str) -> bool:
    return all(
        t in md
        for t in ("MALFORMATION SCAN", "SATISFICING RISK SCAN", "GROUNDING RISK SCAN")
    )


def p_precommit(md: str) -> bool:
    return (
        "## PHASE 0: PRECOMMIT + CLASSIFY" in md
        and "PRECOMMIT:" in md
        and "What would prove this answer wrong" in md
    )


def p_panel_not_self_judged(md: str) -> bool:
    return (
        "LENS-CAST" in md
        and "did not write any candidate" in md
        and "WINNER:" in md
        and "## PANEL" in md
    )


def p_refute_default(md: str) -> bool:
    # The named rule AND the default verdict it produces. A bare "refuted" is too weak: it is
    # trivially satisfied by any stray "REFUTED" token, so it could never fail.
    return "Refute-default" in md and "REFUTED" in md


def p_pinned_floor(md: str) -> bool:
    return "pinned floor" in md and "BLOCK" in md


def p_receipt(md: str) -> bool:
    return "tfc_learn routing" in md and "## PREDICTION" in md


def p_cost_contract(md: str) -> bool:
    return "TIER D COST" in md and "cost contract" in md


def p_falsifiability(md: str) -> bool:
    return "## FALSIFIABILITY" in md and "EXPERIMENT:" in md


def p_required_sections(md: str) -> bool:
    return all(s in md for s in REQUIRED_SECTIONS)


def p_no_em_dash_outside_managed(md: str) -> bool:
    return " \u2014 " not in strip_managed(md)


# ── checks: each is a (title, predicate, mutation) triple ──────────────────────

MECHANISMS = [
    (
        "three-axes (grounding scored independently)",
        p_three_axes,
        ("GROUNDING RISK SCAN", ""),
    ),
    (
        "precommit-before-answer (V3 ordering)",
        p_precommit,
        ("PRECOMMIT:", ""),
    ),
    (
        "panel-is-selfscore-in-costume (RED): verdict needs a panel that did not author it",
        p_panel_not_self_judged,
        ("did not write any candidate", ""),
    ),
    (
        "judge-is-yes-man (RED): refute-default stated",
        p_refute_default,
        ("Refute-default", ""),
    ),
    (
        "pinned-floor-unlearnable (RED): floors asserted + violation BLOCKS",
        p_pinned_floor,
        ("pinned floor", "tunable weight"),
    ),
    (
        "receipt-never-arrives (RED): prediction scored against a recorded outcome",
        p_receipt,
        ("tfc_learn routing", ""),
    ),
    (
        "cost-contract (ambition floor + depth ceiling)",
        p_cost_contract,
        ("TIER D COST", ""),
    ),
    (
        "falsifiability + EXPERIMENT framing (pinned floor)",
        p_falsifiability,
        ("EXPERIMENT:", ""),
    ),
    (
        "required-sections present",
        p_required_sections,
        # Anchor must not be a prefix of the replacement, or the section would survive the
        # mutation as a substring and the check could never fail.
        ("## PANEL", "## NOT-A-PANEL"),
    ),
    (
        "voice: no em dash outside the managed hook",
        p_no_em_dash_outside_managed,
        (None, None),  # mutation built separately below
    ),
]


def check_mechanisms() -> str:
    for title, pred, (needle, repl) in MECHANISMS:
        require(pred(MD), f"mechanism missing from SKILL.md: {title}")
        # Negative half: the mutation must be DETECTED.
        if needle is None:
            mutant = strip_managed(MD) + "\nsome prose with an em dash \u2014 here\n"
            detected = not p_no_em_dash_outside_managed(mutant)
        else:
            require(needle in MD, f"mutation anchor not found for check: {title}")
            # Replace EVERY occurrence: a marker that survives in a second location is not a
            # mutation, and the check would look stronger than it is.
            mutant = MD.replace(needle, repl)
            detected = not pred(mutant)
        require(
            detected,
            f"the check for '{title}' cannot fail: mutating '{needle}' was not detected",
        )
    return f"{len(MECHANISMS)} mechanisms, each proven detectable on mutation"


def check_spec() -> str:
    require(SPEC.get("id") == "super-reasoner", "spec.id must stay 'super-reasoner'")
    require(SPEC.get("version") == "4.0.0", f"spec.version is {SPEC.get('version')}, expected 4.0.0")
    secs = SPEC.get("required_sections") or []
    require(secs == REQUIRED_SECTIONS, f"required_sections drift: {secs}")
    edges = SPEC.get("sharp_edges") or []
    require(len(edges) >= 13, f"only {len(edges)} sharp edges, expected >= 13")
    missing = [e.get("id") for e in edges if not (e.get("solution") or "").strip()]
    require(not missing, f"sharp edges without a solution: {missing}")
    # Every declared sharp edge must be named in the shipped SKILL.md.
    unnamed = [e.get("id") for e in edges if e.get("id") not in MD]
    require(not unnamed, f"sharp edges declared but absent from SKILL.md: {unnamed}")
    phases = SPEC.get("phases") or []
    require(len(phases) >= 3, f"only {len(phases)} phases declared")
    for p in phases:
        require(p.get("artifact"), f"phase without artifact: {p.get('name')}")
        require(p.get("acceptance"), f"phase without acceptance: {p.get('name')}")
    triggers = SPEC.get("triggers") or []
    short = [t for t in triggers if len(str(t).split()) < 4]
    require(not short, f"triggers under 4 words: {short}")
    return f"v{SPEC.get('version')}, {len(edges)} sharp edges, {len(phases)} phases"


def check_evals() -> str:
    tasks = EVALS.get("golden_tasks") or []
    require(len(tasks) >= 10, f"only {len(tasks)} golden tasks, expected >= 10")
    for t in tasks:
        require(t.get("must"), f"task without a `must`: {t.get('id')}")
        require(t.get("must_not"), f"task without a `must_not`: {t.get('id')}")
    ids = [t.get("id") for t in tasks]
    need = {
        "adversarial-panel-tempting-trivial",
        "malformed-false-dichotomy",
        "evidence-free-future-claim",
        "contested-well-formed-high-risk",
        "trivial-factual-low-risk",
    }
    absent = sorted(need - set(ids))
    require(not absent, f"held-out set missing required cases: {absent}")
    return f"{len(tasks)} held-out tasks, each with must + must_not"


def check_validations() -> str:
    vpath = SKILL_DIR / "validations.yaml"
    v = yaml.safe_load(vpath.read_text(encoding="utf-8"))
    gates = v.get("validations") or []
    ids = {g.get("id") for g in gates}
    need = {
        "precommit-before-classify",
        "three-axes-scored",
        "panel-not-self-judged",
        "falsifiability-and-prediction",
        "pinned-floors-named",
    }
    absent = sorted(need - ids)
    require(not absent, f"v4 gates absent from validations.yaml: {absent}")
    data_gates = [g for g in gates if g.get("kind")]
    for g in data_gates:
        require(g.get("kind") in ("contains", "section", "file-exists"), f"bad kind: {g.get('id')}")
    return f"{len(gates)} gates ({len(data_gates)} data-authored)"


def slice_between(text: str, start: str, ends: tuple[str, ...]) -> str:
    i = text.find(start)
    if i == -1:
        return ""
    j = len(text)
    for e in ends:
        k = text.find(e, i + len(start))
        if k != -1:
            j = min(j, k)
    return text[i:j]


def check_placement() -> str:
    """Placement, not merely presence.

    Every gate in validations.yaml is a `contains` data-check, which asserts a string exists
    SOMEWHERE in SKILL.md. A panel marker that survives only in the Output Contract prose would
    therefore keep a gate green after the Tier D pattern itself was deleted. These assertions
    make the requirement placement-aware, which the data-check interpreter cannot do.
    """
    tier_d = slice_between(MD, "### TIER D", ("\n---\n",))
    require(len(tier_d) > 400, "Tier D section not found or implausibly small")
    for m in ("D-GEN", "LENS-CAST", "D-JUDGE", "did not write any candidate", "D-SELECT", "WINNER:"):
        require(m in tier_d, f"panel marker '{m}' is NOT inside the Tier D section")

    phase0 = slice_between(MD, "## PHASE 0: PRECOMMIT + CLASSIFY", ("\n---\n",))
    require(len(phase0) > 500, "Phase 0 block not found or implausibly small")
    for m in ("PRECOMMIT:", "MALFORMATION SCAN", "SATISFICING RISK SCAN", "GROUNDING RISK SCAN"):
        require(m in phase0, f"'{m}' is NOT inside the Phase 0 block")

    # Negative half: delete the Tier D section and the crux marker must disappear. If it
    # survives elsewhere, the marker is decorative and the section was never load-bearing.
    without_tier_d = MD.replace(tier_d, "")
    require(
        "did not write any candidate" not in without_tier_d,
        "the crux marker survives outside Tier D: this gate is placement-blind again",
    )
    survivors = without_tier_d.count("LENS-CAST")
    return f"panel + Phase 0 markers confined to their sections (LENS-CAST survives elsewhere x{survivors}, non-load-bearing)"


def main() -> int:
    print(f"super-reasoner selftest  ({SKILL_DIR})")
    check("mechanisms (positive + mutation-detected)", check_mechanisms)
    check("spec.yaml contract", check_spec)
    check("evals.yaml held-out set", check_evals)
    check("validations.yaml v4 gates", check_validations)
    check("placement (markers inside their sections)", check_placement)

    failed = [n for n, ok, _ in RESULTS if not ok]
    print()
    if failed:
        print(f"{len(RESULTS) - len(failed)}/{len(RESULTS)} checks passed. FAILED: {failed}")
        return 1
    print(f"all {len(RESULTS)} checks passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
